// Writes src/holiday-names.ts: each holiday's name in the languages that have
// no column of their own in holidays.ts. The names come from the content
// dictionaries in packages/db/prisma/data/content-translations.
//
// Run from packages/shared after those dictionaries change:
//   node scripts/make-holiday-names.mjs

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const folder = new URL('../../db/prisma/data/content-translations/', import.meta.url);
const holidays = readFileSync(new URL('../src/holidays.ts', import.meta.url), 'utf8');
const english = [...holidays.matchAll(/^const [A-Z_]+ = \["((?:[^"\\]|\\.)+)"/gm)].map((match) => JSON.parse(`"${match[1]}"`));
if (english.length === 0) throw new Error('No holiday names found in holidays.ts');

const names = Object.fromEntries(english.map((name) => [name, {}]));
const languages = [];
for (const file of readdirSync(folder).filter((name) => /^[a-z]{2}\.json$/.test(name)).sort()) {
  const language = file.slice(0, 2);
  const dictionary = JSON.parse(readFileSync(new URL(file, folder), 'utf8'));
  languages.push(language);
  for (const name of english) {
    if (!dictionary[name]) throw new Error(`${file}: no translation for the holiday "${name}"`);
    names[name][language] = dictionary[name];
  }
}

const body = english
  .map((name) => `  ${JSON.stringify(name)}: ${JSON.stringify(names[name])},`)
  .join('\n');
writeFileSync(
  new URL('../src/holiday-names.ts', import.meta.url),
  `// GENERATED by scripts/make-holiday-names.mjs from the content dictionaries. Do not edit by hand.
//
// Each holiday's name, keyed by its English name, in the languages that
// holidays.ts does not spell out itself.

import type { LocalizedText } from "./checklists.js";

export const HOLIDAY_NAMES: Record<string, LocalizedText> = {
${body}
};
`,
);
console.log(`Wrote ${english.length} holiday names in ${languages.length} languages (${languages.join(', ')}).`);
